    private void BTN_ModificarPersonalActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_BTN_ModificarPersonalActionPerformed
       /* VALIDAR QUE SE HAYA SELECCIONADO UN REGISTRO */

String codStr = txtId_Personal.getText().trim();

String nombres = TxtNombre.getText().trim();
String apellidos = TxtApellidos.getText().trim();
String dni = TxtDNI.getText().trim();
String direccion = TextDireccion.getText().trim();
String telefono = TextTelefono.getText().trim();
String correo = TextCorreo.getText().trim();
String observaciones = TextObservaciones.getText().trim();


/* OBTENER LOS DATOS DE LOS COMBOBOX */

String tipoPersonal = jComboTipoPersonal.getSelectedItem().toString();
String cargo = jComboCargo.getSelectedItem().toString();
String area = jComboArea.getSelectedItem().toString();
String sucursal = jComboSucursal.getSelectedItem().toString();

/* VALIDAR TODOS LOS CAMPOS */

if (codStr.isEmpty()
        || nombres.isEmpty()
        || apellidos.isEmpty()
        || dni.isEmpty()
        || direccion.isEmpty()
        || telefono.isEmpty()
        || correo.isEmpty()
        || observaciones.isEmpty()
        
        || tipoPersonal.equals("<<Seleccionar>>")
        || cargo.equals("<<Seleccionar>>")
        || area.equals("<<Seleccionar>>")
        || sucursal.equals("<<Seleccionar>>")) {

    JOptionPane.showMessageDialog(
            this,
            "Seleccione un Personal y complete todos los campos.",
            "Campos requeridos",
            JOptionPane.WARNING_MESSAGE
    );

    return;
}

/* CONVERTIR EL CÓDIGO */

int codigo;

try {

    codigo = Integer.parseInt(codStr);

} catch (NumberFormatException e) {

    JOptionPane.showMessageDialog(
            this,
            "El código del Personal no es válido.",
            "Código incorrecto",
            JOptionPane.WARNING_MESSAGE
    );

    return;
}

/* VALIDAR ESTADO */



/* OBTENER LOS ID DE LAS CLAVES FORÁNEAS */

try {

    int idTipoPersonal = conexionS_BD.obtenerIdTipoPersonal(tipoPersonal);
    int idCargo = conexionS_BD.obtenerIdCargoPersonal(cargo);
    int idArea = conexionS_BD.obtenerIdAreaPersonal(area);
    int idSucursal = conexionS_BD.obtenerIdSucursalPersonal(sucursal);

    /* VALIDAR QUE SE HAYAN ENCONTRADO LOS ID */

    if (idTipoPersonal == -1
            || idCargo == -1
            || idArea == -1
            || idSucursal == -1) {

        JOptionPane.showMessageDialog(
                this,
                "No se pudo obtener una de las claves foráneas.",
                "Error",
                JOptionPane.WARNING_MESSAGE
        );

        return;
    }

    /* CONFIRMACIÓN */

    int respuesta = JOptionPane.showConfirmDialog(
            this,
            "¿Desea modificar Personal?",
            "Confirmación",
            JOptionPane.YES_NO_OPTION
    );

    if (respuesta == JOptionPane.YES_OPTION) {

        /* MODIFICAR PERSONAL */

        conexionS_BD.modificarPersonal(
                codigo,
                idTipoPersonal,
                idCargo,
                idArea,
                idSucursal,
                nombres,
                apellidos,
                dni,
                direccion,
                telefono,
                correo,
                observaciones
                //estado
        );

        /* MENSAJE DE ÉXITO */

        JOptionPane.showMessageDialog(
                this,
                "Personal modificado correctamente",
                "Modificación exitosa",
                JOptionPane.INFORMATION_MESSAGE
        );

        /* ACTUALIZAR TABLA */

        this.mostrarDatosTablaPersonal();

        /* LIMPIAR CAMPOS */

        txtId_Personal.setText("");
        TxtNombre.setText("");
        TxtApellidos.setText("");
        TxtDNI.setText("");
        TextDireccion.setText("");
        TextTelefono.setText("");
        TextCorreo.setText("");
        TextObservaciones.setText("");
        

        jComboTipoPersonal.setSelectedIndex(0);
        jComboCargo.setSelectedIndex(0);
        jComboArea.setSelectedIndex(0);
        jComboSucursal.setSelectedIndex(0);

        /* BOTONES */

        BTN_CERRARPersonal.setEnabled(false);
        BTN_ModificarPersonal.setEnabled(false);
        BTN_GUARDARPersonal.setEnabled(true);
    }

} catch (SQLException ex) {

    JOptionPane.showMessageDialog(
            this,
            "Error al modificar Personal:\n" + ex.getMessage(),
            "Error de base de datos",
            JOptionPane.ERROR_MESSAGE
    );
}
    }//GEN-LAST:event_BTN_ModificarPersonalActionPerformed

