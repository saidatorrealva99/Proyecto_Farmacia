public void mostrarDatosTablaPersonal() {
    JTABLE_Personal.setAutoCreateRowSorter(true);

    // Limpia la tabla antes de mostrar nuevos datos
    modeloTablaPersonal.setRowCount(0);

    try {
        // Llama al método que devuelve los datos de Personal
        ResultSet rs = conexionS_BD.listarPersonal();

        // Recorre cada fila del resultado y agrega a la tabla
        while (rs.next()) {

            Object[] fila = {
                rs.getInt("id_personal"),
                rs.getString("nombre_tipo_personal"),
                rs.getString("nombre_cargo"),
                rs.getString("nombre_area"),
                rs.getString("nombre_sucursal"),
                rs.getString("nombres"),
                rs.getString("apellidos"),
                rs.getString("dni"),
                rs.getString("direccion"),
                rs.getString("telefono"),
                rs.getString("correo"),
                rs.getString("observaciones"),
                rs.getString("estado_texto")
            };

            modeloTablaPersonal.addRow(fila);
        }

    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this,
                "Error al mostrar Personal:\n" + e.getMessage(),
                "Error de consulta",
                JOptionPane.ERROR_MESSAGE);
    }
}

